/** '9.85' → 9850（浮動小数点を使わずに桁をずらす） */
function toRate(percent) {
  const [i, f = ''] = percent.split('.');
  return Number(i) * 1000 + Number(f.padEnd(3, '0'));
}

/** insurerRates に入れるドキュメント（協会けんぽ分） */
export function kyokaiRateDocs() {
  const rate = (id, rateType, prefecture, validFrom, percent) => ({
    id,
    data: { insurerId: 'kyokai', rateType, prefecture, validFrom, rate: toRate(percent), employeeShare: 500 },
  });
  return [
    ...HEALTH_2026.map(([pref, pct], i) =>
      rate(`kyokai-health-2026-03-${String(i + 1).padStart(2, '0')}`, 'health', pref, '2026-03', pct),
    ),
    rate('kyokai-care-2026-03', 'care', null, '2026-03', '1.62'),
    rate('kyokai-childSupport-2026-04', 'childSupport', null, '2026-04', '0.23'),
  ];
}

/** pensionRates に入れるドキュメント（厚生年金。2017年9月分から18.3%で固定） */
export function pensionRateDocs() {
  return [{ id: '2017-09', data: { validFrom: '2017-09', rate: toRate('18.3'), employeeShare: 500 } }];
}
